// TIDELINE PRESS — seeded randomness.
// Every random choice on the render path comes from here, so a cover drawn
// twice is byte-identical. No Math.random() anywhere in the app.

export function hashSeed(text) {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Convenience: a fresh PRNG for one named thing (a cover, a photo, a sky).
export function rngFor(name) {
  return mulberry32(hashSeed(name));
}
